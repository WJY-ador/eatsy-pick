/** 공백, 괄호, (주), 주식회사, 유한회사 제거 후 소문자 */
export function normalizeName(name: string): string {
  return name
    .replace(/\(주\)|㈜|주식회사|유한회사/g, "")
    .replace(/[\s()[\]{}<>]/g, "")
    .toLowerCase();
}

const NORMALIZED = FRANCHISE_KEYWORDS.map(normalizeName);

export function isFranchise(name: string, category?: string): boolean {
  if (category === "푸드코트") return true;
  const n = normalizeName(name);
  // 이름 끝이 "직영점"이면 체인으로 본다. "~점"만으로는 보지 않는다.
  if (n.endsWith("직영점")) return true;
  return NORMALIZED.some((k) => k.length > 0 && n.includes(k));
}
